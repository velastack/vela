import process from 'node:process';
import { Command } from 'commander';
import * as p from '@clack/prompts';
import { helpConfig } from '../../lib/help.ts';
import { runPattern } from '../../lib/pattern-runner.ts';
import { runCommand } from './_shared.ts';

export const shop = new Command('shop')
	.description('destroy the shop pages generated by `vela generate shop`')
	.option('-y, --yes', 'skip confirmation prompt')
	.allowExcessArguments(true)
	.configureHelp(helpConfig)
	.action((opts: { yes?: boolean }, cmd) =>
		runCommand(async () => {
			if (!opts.yes) {
				const ok = await p.confirm({
					message:
						'Destroy the shop? Removes the listing and product pages (and src/lib/catalog.ts on WhatsApp). The cart and payments stay.',
					initialValue: false
				});
				if (p.isCancel(ok) || !ok) {
					p.cancel('Operation cancelled.');
					process.exit(0);
				}
			}
			await runPattern(
				'destroy-shop',
				cmd.args,
				{ destructive: true },
				{
					summary: 'Destroyed the shop.',
					task: {
						title: 'Destroying the shop',
						success: 'Destroyed the shop',
						error: 'Failed to destroy the shop'
					}
				}
			);
		}, 'Failed to destroy the shop.')
	);
